#!/usr/bin/env node
// Regenerates THIRD-PARTY-NOTICES.md: every third-party Rust crate linked into
// the DropBeam app and every npm package bundled into its web UI, with its
// licence and the full licence/notice texts (identical texts printed once).
//
//   node scripts/third-party-notices.mjs        # from the repo root
//
// Needs `cargo` (reads `cargo metadata`; crate sources must be fetched, which
// cargo metadata does) and an installed node_modules (`npm ci`). Run it when
// dependencies change and before each release; commit the result.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const FIRST_PARTY_CRATES = new Set(['app', 'dropbeam-lab', 'tauri-plugin-native-ui'])
const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright|unlicense)([-._].*)?$/i

function licenseTexts(dir) {
  let names = []
  try { names = fs.readdirSync(dir) } catch { return [] }
  return names
    .filter((n) => LICENSE_FILE.test(n) && fs.statSync(path.join(dir, n)).isFile())
    .sort()
    .map((n) => fs.readFileSync(path.join(dir, n), 'utf8').replace(/\r\n/g, '\n').trim())
    .filter(Boolean)
}

// ---- Rust: crates reachable from the app through normal (non-dev) deps -----
const meta = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked'], {
  cwd: path.join(root, 'src-tauri'), maxBuffer: 1 << 30,
}).toString())
const byId = new Map(meta.packages.map((p) => [p.id, p]))
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]))
const appId = meta.packages.find((p) => p.name === 'app').id
const seen = new Set()
const stack = [appId]
while (stack.length) {
  const id = stack.pop()
  if (seen.has(id)) continue
  seen.add(id)
  for (const d of nodes.get(id)?.deps ?? []) {
    if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg)
  }
}
const crates = [...seen].map((id) => byId.get(id))
  .filter((p) => !FIRST_PARTY_CRATES.has(p.name))
  .map((p) => {
    const dir = path.dirname(p.manifest_path)
    let texts = licenseTexts(dir)
    if (p.license_file) {
      try { texts = [fs.readFileSync(path.join(dir, p.license_file), 'utf8').trim(), ...texts] } catch { /* listed only */ }
    }
    return { kind: 'crate', name: p.name, version: p.version, license: p.license || (p.license_file || texts.length ? 'see licence text' : 'UNKNOWN'), url: p.repository || `https://crates.io/crates/${p.name}`, texts: [...new Set(texts)] }
  })

// ---- npm: production dependencies (what Vite bundles into the UI) ---------
// `npm ls` exits non-zero for extraneous/invalid packages but still prints the
// tree — use its output either way.
const npmLs = (() => {
  try {
    return execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], { cwd: root, maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] })
  } catch (e) { return e.stdout }
})()
const npmTree = JSON.parse(npmLs.toString())
const npmPkgs = new Map()
;(function walk(deps) {
  for (const [name, d] of Object.entries(deps ?? {})) {
    if (!d.path || npmPkgs.has(d.path)) continue
    const pj = JSON.parse(fs.readFileSync(path.join(d.path, 'package.json'), 'utf8'))
    const lic = typeof pj.license === 'string' ? pj.license : pj.license?.type ?? (pj.licenses ?? []).map((l) => l.type).join(' OR ')
    const repo = typeof pj.repository === 'string' ? pj.repository : pj.repository?.url
    npmPkgs.set(d.path, { kind: 'npm', name, version: pj.version, license: lic || 'UNKNOWN', url: (repo || `https://www.npmjs.com/package/${name}`).replace(/^git\+/, ''), texts: licenseTexts(d.path) })
    walk(d.dependencies)
  }
})(npmTree.dependencies)

const all = [...crates, ...npmPkgs.values()]
  .sort((a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }))

// ---- Write: summary table, then each distinct text once --------------------
const textIndex = new Map() // hash -> { text, users: [] }
for (const p of all) {
  p.refs = p.texts.map((t) => {
    const h = createHash('sha256').update(t).digest('hex').slice(0, 10)
    if (!textIndex.has(h)) textIndex.set(h, { text: t, users: [] })
    textIndex.get(h).users.push(`${p.name} ${p.version}`)
    return h
  })
}
const esc = (s) => String(s).replace(/\|/g, '\\|')
const out = []
out.push('# Third-party notices', '')
out.push('DropBeam includes the open-source software listed below. Each component is used under its own licence;',
  'the full licence and notice texts follow the table (identical texts are printed once, with the packages that use them).',
  '', '_Generated by `node scripts/third-party-notices.mjs` — do not edit by hand._', '')
out.push(`${crates.length} Rust crates, ${npmPkgs.size} npm packages.`, '')
out.push('| Component | Version | Licence | Source | Text |', '|---|---|---|---|---|')
for (const p of all) {
  out.push(`| ${esc(p.name)} (${p.kind}) | ${esc(p.version)} | ${esc(p.license)} | ${esc(p.url)} | ${p.refs.length ? p.refs.map((r) => `[${r}](#t-${r})`).join(' ') : 'SPDX text (licence id)'} |`)
}
out.push('', '## Licence texts', '')
for (const [h, { text, users }] of textIndex) {
  out.push(`<a id="t-${h}"></a>`, `### ${h}`, '', `Used by: ${users.join(', ')}`, '', '```text', text.replace(/```/g, "'''"), '```', '')
}
// Components whose package ships no licence file are covered by the standard
// SPDX text of their licence (scripts/licenses/<id>.txt, from spdx/license-list-data).
const spdxDir = path.join(root, 'scripts', 'licenses')
const spdxIds = new Set()
for (const p of all.filter((x) => !x.refs.length)) {
  for (const id of p.license.split(/\s+(?:OR|AND|WITH)\s+|\/|[()]/).map((x) => x.trim()).filter(Boolean)) spdxIds.add(id)
}
out.push('## Standard licence texts', '', 'For the components above whose package does not include a licence file (marked “SPDX text”), the standard text of the named licence applies:', '')
for (const id of [...spdxIds].sort()) {
  const f = path.join(spdxDir, `${id}.txt`)
  if (fs.existsSync(f)) out.push(`### ${id}`, '', '```text', fs.readFileSync(f, 'utf8').trim(), '```', '')
}
const unknown = all.filter((p) => p.license === 'UNKNOWN').map((p) => `${p.name} ${p.version}`)
fs.writeFileSync(path.join(root, 'THIRD-PARTY-NOTICES.md'), out.join('\n'))
console.log(`THIRD-PARTY-NOTICES.md: ${all.length} components, ${textIndex.size} distinct texts` + (unknown.length ? `; NO licence field: ${unknown.join(', ')}` : ''))
